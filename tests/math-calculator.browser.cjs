const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const os=require('node:os');const path=require('node:path');const fs=require('node:fs');
(async()=>{
 const profile=fs.mkdtempSync(path.join(os.tmpdir(),'math-profile-'));
 let context=await chromium.launchPersistentContext(profile,{headless:true,channel:'msedge',viewport:{width:1440,height:1000},locale:'pt-BR'});
 try {
  let page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5003/calculadora');
  const input=page.locator('#math-expression');
  const result=page.locator('#math-result');
  const key=async k=>page.locator(`[data-math="${k}"]`).click();
  await key('2');await key('+');await key('3');await key('equals');assert.equal(await result.innerText(),'5');
  await key('*');await key('4');await key('equals');assert.equal(await result.innerText(),'20');
  await input.focus();await page.keyboard.press('Escape');await page.keyboard.type('0.1+0,2');await page.keyboard.press('Enter');assert.equal(await result.innerText(),'0,3');
  await key('clear');await page.keyboard.type('123');await page.keyboard.press('Backspace');assert.equal(await input.inputValue(),'12');
  await key('sign');await key('equals');assert.equal(await result.innerText(),'-12');
  await input.fill('200+10%');await page.keyboard.press('Enter');assert.equal(await result.innerText(),'220');
  await input.fill('(2+3)*4');await page.keyboard.press('Enter');assert.equal(await result.innerText(),'20');
  await input.fill('1/0');await page.keyboard.press('Enter');assert.match(await page.locator('#math-error').innerText(),/zero/);
  await input.fill('2+');await page.keyboard.press('Enter');assert.match(await page.locator('#math-error').innerText(),/inválida/);
  await input.fill('25*2');await page.keyboard.press('Enter');
  await page.locator('#math-history-toggle').click();assert.equal(await page.locator('#math-history').isVisible(),true);
  const historyResult=page.locator('#math-history-list button').first();
  await input.fill('');await historyResult.click();assert.equal(await input.inputValue(),'50');
  await input.fill('150 + ');await input.evaluate(el=>el.setSelectionRange(6,6));await historyResult.click();assert.equal(await input.inputValue(),'150 + 50');
  await input.fill('100 + 20');await input.evaluate(el=>el.setSelectionRange(6,6));await historyResult.click();assert.equal(await input.inputValue(),'100 + 5020');
  assert.deepEqual(await input.evaluate(el=>[el.selectionStart,el.selectionEnd,document.activeElement===el]),[8,8,true]);
  await input.fill('100 + 20');await input.evaluate(el=>el.setSelectionRange(6,8));await historyResult.click();assert.equal(await input.inputValue(),'100 + 5020');
  await input.fill('1+');await input.evaluate(el=>el.setSelectionRange(0,0));await page.locator('#draft-notes').focus();await historyResult.click();assert.equal(await input.inputValue(),'1+50');
  assert.equal(await result.innerText(),'50');
  const count=await page.locator('#math-history-list li').count();
  await page.locator('#draft-notes').fill('Texto preservado\nSegunda linha');
  assert.equal(await page.locator('#draft-notes').getAttribute('rows'),'2');assert.equal(await page.locator('#draft-notes').getAttribute('maxlength'),'5000');
  await page.reload();assert.equal(await page.locator('#math-history-list li').count(),count);assert.match(await page.locator('#draft-notes').inputValue(),/Texto preservado/);
  await page.locator('#math-history-toggle').click();
  assert.equal(await page.locator('.math-layout > #math-history').count(),1);
  const controlsBox=await page.locator('.math-controls').boundingBox(), historyBox=await page.locator('#math-history').boundingBox();
  assert.ok(historyBox.x>controlsBox.x+controlsBox.width,'History is alongside desktop controls');
  await page.screenshot({path:path.join(os.tmpdir(),'math-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:path.join(os.tmpdir(),'math-mobile.png'),fullPage:true});
  await context.close();
  context=await chromium.launchPersistentContext(profile,{headless:true,channel:'msedge'});
  page=await context.newPage();await page.goto('http://127.0.0.1:5003/calculadora');
  assert.equal(await page.locator('#math-history-list li').count(),count);
  await page.locator('#math-history-toggle').click();
  page.once('dialog',d=>d.dismiss());await page.locator('#math-history-clear').click();assert.equal(await page.locator('#math-history-list li').count(),count);
  page.once('dialog',d=>d.accept());await page.locator('#math-history-clear').click();await page.reload();assert.equal(await page.locator('#math-history-list li').count(),0);
  assert.deepEqual(errors,[]);
  console.log('PASS: buttons, keyboard, percentages, invalid input, history reopen/persistence/clear, all cursor insertions, notes and mobile.');
 } finally {await context.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
