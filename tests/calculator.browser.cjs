// Run with Playwright available and tests/browser_server.py listening on port 5003.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const os=require('node:os');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 try {
  const page=await browser.newPage({locale:'pt-BR',viewport:{width:1440,height:1000}});
  const errors=[],mutations=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.method()!=='GET')mutations.push(r.url());});
  await page.goto('http://127.0.0.1:5003/calculadora');
  const add=async(amount,client,method)=>{
   await page.locator('#draft-amount').fill(amount);
   await page.locator('#draft-client').fill(client);
   await page.locator('#draft-date').fill('2026-11-03');
   await page.locator('#draft-method').selectOption(method);
   await page.locator('#draft-save').click();
  };
  await add('100,10','Ana','cheque');
  await add('0,20','Ana','cheque');
  await add('50,15','Bia','dinheiro');
  assert.equal(await page.locator('#draft-rows tr').count(),3);
  await page.locator('#draft-notes').fill('Conferência de exemplo\nSem efeito nos lotes.');
  await page.locator('#draft-generate').click();
  assert.equal(await page.locator('#draft-total').innerText(),'R$ 150,45');
  assert.equal(await page.locator('#draft-cheque').innerText(),'R$ 100,30');
  assert.equal(await page.locator('#draft-cash').innerText(),'R$ 50,15');
  assert.equal(await page.locator('#draft-clients tr').count(),2);
  assert.match(await page.locator('#draft-report-rows').innerText(),/03\/11\/2026/);
  await page.screenshot({path:path.join(os.tmpdir(),'calculadora-desktop.png'),fullPage:true});
  await page.reload();
  assert.equal(await page.locator('#draft-rows tr').count(),3);
  assert.match(await page.locator('#draft-notes').inputValue(),/Conferência/);
  await page.locator('[data-action=edit]').first().click();
  await page.locator('#draft-amount').fill('200,10');
  await page.locator('#draft-save').click();
  await page.locator('#draft-generate').click();
  assert.equal(await page.locator('#draft-total').innerText(),'R$ 250,45');
  page.once('dialog',d=>d.dismiss());
  await page.locator('[data-action=delete]').nth(1).click();
  assert.equal(await page.locator('#draft-rows tr').count(),3);
  page.once('dialog',d=>d.accept());
  await page.locator('[data-action=delete]').nth(1).click();
  assert.equal(await page.locator('#draft-rows tr').count(),2);
  assert.equal(await page.locator('#draft-report').isVisible(),false);
  await page.locator('#draft-generate').click();
  assert.equal(await page.locator('#draft-total').innerText(),'R$ 250,25');
  await add('1,123','Inválido','dinheiro');
  assert.equal(await page.locator('#draft-rows tr').count(),2);
  await page.locator('#draft-amount').fill('1');
  await page.locator('#draft-client').fill('<img src=x onerror=alert(1)>');
  await page.locator('#draft-save').click();
  assert.equal(await page.locator('#draft-rows img').count(),0);
  await page.locator('#draft-generate').click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(os.tmpdir(),'calculadora-mobile.png'),fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  page.once('dialog',d=>d.accept());
  await page.locator('#draft-clear').click();
  await page.reload();
  assert.equal(await page.locator('#draft-rows tr').count(),0);
  assert.equal(await page.locator('#draft-notes').inputValue(),'');
  await page.goto('http://127.0.0.1:5003/lote/novo');
  assert.equal(await page.locator('#withdrawal').getAttribute('type'),'date');
  assert.match(await page.locator('#withdrawal').inputValue(),/^\d{4}-\d{2}-\d{2}$/);
  assert.deepEqual(errors,[]); assert.deepEqual(mutations,[]);
  console.log('UI OK: totais exatos, edição, exclusão confirmada, sessão, segurança, celular, date picker, nenhuma escrita no servidor.');
  console.log(path.join(os.tmpdir(),'calculadora-desktop.png'));
  console.log(path.join(os.tmpdir(),'calculadora-mobile.png'));
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
